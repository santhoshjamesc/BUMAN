/** Picks a random compliment, avoiding an immediate repeat of `previous`. */
export function pickCompliment(previous?: string | null): string {
  const options = previous ? COMPLIMENTS.filter((c) => c !== previous) : COMPLIMENTS;
  return options[Math.floor(Math.random() * options.length)];
}
